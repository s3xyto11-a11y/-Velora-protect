create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(name) between 2 and 60),
    project_type text not null check (char_length(project_type) between 2 and 80),
    comment text not null check (char_length(comment) between 10 and 600),
    approved boolean not null default false,
    created_at timestamptz not null default now()
);

alter table public.reviews
add column if not exists likes_count integer not null default 0 check (likes_count >= 0);

create table if not exists public.review_likes (
    review_id bigint not null references public.reviews(id) on delete cascade,
    visitor_token uuid not null,
    created_at timestamptz not null default now(),
    primary key (review_id, visitor_token)
);

alter table public.reviews enable row level security;
alter table public.review_likes enable row level security;

revoke all on table public.reviews from anon, authenticated;
revoke all on table public.review_likes from anon, authenticated;
grant select (id, name, project_type, comment, likes_count, created_at) on table public.reviews to anon, authenticated;
grant insert (name, project_type, comment) on table public.reviews to anon, authenticated;
grant usage, select on sequence public.reviews_id_seq to anon, authenticated;

drop policy if exists "Public can read approved reviews" on public.reviews;
create policy "Public can read approved reviews"
on public.reviews
for select
to anon, authenticated
using (approved = true);

drop policy if exists "Visitors can submit pending reviews" on public.reviews;
create policy "Visitors can submit pending reviews"
on public.reviews
for insert
to anon, authenticated
with check (approved = false);

create extension if not exists pgcrypto with schema extensions;

create or replace function public.like_review(p_review_id bigint, p_visitor_token uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
    inserted_rows integer;
    current_likes integer;
begin
    insert into public.review_likes (review_id, visitor_token)
    select p_review_id, p_visitor_token
    where exists (
        select 1 from public.reviews
        where id = p_review_id and approved = true
    )
    on conflict do nothing;

    get diagnostics inserted_rows = row_count;

    if inserted_rows = 1 then
        update public.reviews
        set likes_count = likes_count + 1
        where id = p_review_id and approved = true
        returning likes_count into current_likes;
    else
        select likes_count into current_likes
        from public.reviews
        where id = p_review_id and approved = true;
    end if;

    if current_likes is null then
        raise exception 'Review not found';
    end if;

    return current_likes;
end;
$$;

revoke all on function public.like_review(bigint, uuid) from public, anon, authenticated;
grant execute on function public.like_review(bigint, uuid) to anon, authenticated;

create or replace function public.get_reviews_for_moderation(p_admin_password text)
returns table (
    id bigint,
    name text,
    project_type text,
    comment text,
    approved boolean,
    likes_count integer,
    created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
    if pg_catalog.encode(extensions.digest(p_admin_password, 'sha256'), 'hex') <> 'a1d7b5cf4bbe5aa4ffdd185204312cb932ca20e1eabd674c85c9d77248dbdfe0' then
        raise exception 'Unauthorized' using errcode = '42501';
    end if;

    return query
    select r.id, r.name, r.project_type, r.comment, r.approved, r.likes_count, r.created_at
    from public.reviews as r
    order by r.created_at desc;
end;
$$;

revoke all on function public.get_reviews_for_moderation(text) from public, anon, authenticated;
grant execute on function public.get_reviews_for_moderation(text) to anon, authenticated;

create or replace function public.moderate_review(p_review_id bigint, p_action text, p_admin_password text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
    if pg_catalog.encode(extensions.digest(p_admin_password, 'sha256'), 'hex') <> 'a1d7b5cf4bbe5aa4ffdd185204312cb932ca20e1eabd674c85c9d77248dbdfe0' then
        raise exception 'Unauthorized' using errcode = '42501';
    end if;

    if p_action = 'approve' then
        update public.reviews set approved = true where id = p_review_id;
    elsif p_action = 'hide' then
        update public.reviews set approved = false where id = p_review_id;
    elsif p_action = 'delete' then
        delete from public.reviews where id = p_review_id;
    else
        raise exception 'Invalid moderation action';
    end if;

    return found;
end;
$$;

revoke all on function public.moderate_review(bigint, text, text) from public, anon, authenticated;
grant execute on function public.moderate_review(bigint, text, text) to anon, authenticated;
